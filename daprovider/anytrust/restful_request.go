package anytrust

import (
	"context"
	"net/http"
)

// doRestfulGet keeps cancellation attached to every AnyTrust REST request.
func doRestfulGet(ctx context.Context, url string) (*http.Response, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	return http.DefaultClient.Do(req)
}
